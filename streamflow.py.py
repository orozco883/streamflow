"""### Part 5 - Average U.S. Daily Birth Data

You will now create a graph using average daily birth data in the U.S.

### Numpy Array Creation & Slicing

Slice the array to create the x and y-axis values. These will correspond to the following columns in the CSV linked on the HW instructions page:

*   x - Date
*   y_1 - Births
"""

import numpy as np

data = np.genfromtxt(
    '2012-US-Birth-Rates.csv',
    delimiter=',',
    skip_header=1,
    dtype=str
)

x = data[:, 0]
y_1 = data[:, 1].astype(float)

"""### Graphing the Data

Plot x and y_1 with the elements shown in the instructions in the code block below.
"""

import matplotlib.pyplot as plt
import pandas as pd

dates = pd.to_datetime(x)
births = y_1

plt.figure(figsize=(12, 6))

plt.plot(dates, births, color='steelblue', linewidth=2)

plt.title('Average U.S. Daily Births (2012)')
plt.xlabel('Date')
plt.ylabel('Number of Births')
plt.grid(True)

holidays = {
    "New Year's Day": '2012-01-01',
    "July 4th": '2012-07-04',
    "Halloween": '2012-10-31',
    "Thanksgiving": '2012-11-22',
    "Christmas": '2012-12-25'
}

for holiday, date in holidays.items():
    holiday_date = pd.Timestamp(date)
    index = np.argmin(abs(dates - holiday_date))
    plt.annotate(
        holiday,
        xy=(dates[index], births[index]),
        xytext=(0, 40),
        textcoords='offset points',
        arrowprops=dict(
            arrowstyle='->',
            connectionstyle='arc3,rad=0.2',
            color='red'
        ),
        fontsize=9,
        ha='center'
    )

plt.xticks(rotation=45)
plt.tight_layout()
plt.show()