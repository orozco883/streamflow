import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

# AI assisted with setting up the beam variables.
# These values represent the beam length, reactions, and loads.

L = 6
RA = 170
RB = 410
P1 = 100
q1 = 120
q2 = 120

# Create 500 evenly spaced points along the beam
x = np.linspace(0, L, 500)

# Create an array of zeros to store shear values
V = np.zeros_like(x)

for i in range(len(x)):
    if x[i] < 2:
        V[i] = RA - (q1 * x[i])
    elif x[i] < 4:
        V[i] = RA - (q1 * 2) - P1
    else:
        V[i] = RA - (q1 * 2) - P1 + RB - (q2 * (x[i] - 4))

plt.figure(figsize=(8, 6))
plt.plot(x, V, color='tab:blue')
plt.fill_between(x, V, 0, color='lightblue')
plt.axhline(0, color='black', linewidth=1)

plt.title('Shear Diagram')
plt.xlabel('x (ft)')
plt.ylabel('V (lb)')

plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

# Part 1b - Moment Diagram

L = 6
RA = 170
RB = 410
P1 = 100
q1 = 120
q2 = 120

x = np.linspace(0, L, 500)
M = np.zeros_like(x)

# Calculate the bending moment along the beam
for i in range(len(x)):
    if x[i] < 2:
        M[i] = (RA * x[i]) - (q1 * x[i]**2 / 2)
    elif x[i] < 4:
        M[i] = (RA * x[i]) - (q1 * 2 * (x[i] - 1)) - (P1 * (x[i] - 2))
    else:
        M[i] = (RA * x[i]) - (q1 * 2 * (x[i] - 1)) - (P1 * (x[i] - 2)) + (RB * (x[i] - 4)) - (q2 * (x[i] - 4)**2 / 2)

# Graph the moment diagram
plt.figure(figsize=(8, 6))
plt.plot(x, M, color='tab:blue')
plt.fill_between(x, M, 0, color='lightblue')
plt.axhline(0, color='black', linewidth=1)

plt.title('Moment Diagram')
plt.xlabel('x (ft)')
plt.ylabel('M (lb-ft)')

plt.show()

